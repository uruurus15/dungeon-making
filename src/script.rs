/// まだ話していない 魔法屋の新入荷(記録のキー, 台詞)
pub fn magic_pending(g: &Game) -> Vec<(String, Vec<String>)> {
    let mut v = vec![];
    for (f, n) in MAGIC_SHOP_UNLOCK {
        let key = format!("magic:item:{}", n);
        if g.reached >= *f && !g.talks_seen.contains(&key) {
            let lines: Vec<String> = MAGIC_ITEM_TALK.iter().find(|(k, _)| k == n).map(|(_, l)| l.iter().map(|x| x.to_string()).collect()).unwrap_or_else(|| vec![format!("{}が 入荷したぞい。", n)]);
            v.push((key, lines));
        }
    }
    for s in SPELLS {
        let key = format!("magic:spell:{}", s.id);
        if g.spell_for_sale(s) && !g.talks_seen.contains(&key) {
            let lines = spell_talk(s.id);
            if !lines.is_empty() {
                v.push((key, lines));
            }
        }
    }
    // はじめからでない ゲームは 初めての来店で 今ある品を 一度に話さない(いまの品揃えを 見たことにする)
    if !tour_on(g) && !g.talks_seen.iter().any(|k| k.starts_with("magic:")) && !v.is_empty() {
        return v.into_iter().map(|(k, _)| (k, vec![])).collect();
    }
    v
}

