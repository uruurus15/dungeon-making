/// 村長と話したあとの愚痴(f+種類で 出たり出なかったり)
fn grumble(f: usize, boss: bool) -> Vec<String> {
    if (f + boss as usize) % 2 == 1 {
        return vec![];
    }
    GRUMBLE[(f + boss as usize / 2 + f / 2) % GRUMBLE.len()].iter().map(|l| l.to_string()).collect()
}

