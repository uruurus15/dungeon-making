fn spec_text(name: &str) -> String {
    let (Some(d), Some(i)) = (ROOM_DEFS.iter().find(|r| r.name == name), item(name)) else { return String::new() };
    let door = if chest_tier(name).is_some() { "カギで開く" } else if d.open4 { "4方向から入れる" } else { "入口は1つ" };
    format!("({}x{}の部屋。{}。{}G)", d.w, d.h, door, i.buy)
}

/// 家具屋に着いたとき、まだ説明していない部屋の話(新入荷のぶんだけ)
pub fn furniture_lines(g: &Game, greeted: bool) -> Vec<String> {
    let new: Vec<&'static str> = g.furniture_stock().into_iter().filter(|n| !g.talks_seen.contains(&format!("furn:{}", n))).collect();
    if new.is_empty() {
        return vec![];
    }
    let first = g.talks_seen.iter().all(|k| !k.starts_with("furn:"));
    let mut v: Vec<String> = vec![];
    if first && greeted {
        // あいさつまわり: 自己紹介は hello_lines で済んでいる
        v.push("さっそく 部屋を ひとつずつ 説明するぜ!".to_string());
    } else if first {
        v.push("メイミ「ちょっとおじさん、このお店 散らかりすぎじゃない? ちゃんと掃除してるの?」".to_string());
        v.push("※なにぃ? 職人の工房は これでいいんだよ!".to_string());
        v.push("※アレン「ごめんなさい、メイミが失礼なことを…。」".to_string());
        v.push("おう、アレン! ここは家具屋だ。ダンジョンの部屋を売ってるぜ。".to_string());
    } else {
        match g.talks_seen.len() % 3 {
            0 => {
                v.push("メイミ「また値上がりしてるんじゃないでしょうね?」".to_string());
                v.push("※するかい! うちは 良心的だぞ!".to_string());
            }
            1 => {
                v.push("メイミ「アレン、先に言っておくけど、あのおじさんの話 長いわよ。」".to_string());
                v.push("※聞こえてるぞ、メイミ!".to_string());
            }
            _ => {}
        }
        v.push("お、新しい部屋が入ったぜ!".to_string());
    }
    let mei = g.party[2].joined;
    for n in new {
        let talk = FURNITURE_TALK.iter().find(|(k, _)| *k == n).map(|(_, t)| *t).unwrap_or("新しい部屋だ。");
        v.push(talk.to_string());
        if !(first && greeted) {
            v.push(format!("＊{}", spec_text(n)));
        }
    }
    clean(v, mei)
}

/// 家に着いたときの イベント(台詞を返し、話した記録をつける)。台詞が無ければ空
/// 順番: あいさつまわり → 新入荷の話 → 前に受けた依頼のようす → 新しい依頼
pub fn on_enter(g: &mut Game, kind: ShopKind) -> Vec<String> {
    let mut v = vec![];
    let mei = g.party[2].joined;
    let greeted = tour_pending(g, kind);
    if greeted {
        v.extend(hello_lines(kind));
        g.talks_seen.insert(hello_key(kind));
        if kind == ShopKind::Armor && g.party[0].equip[0].is_none() && g.count("ナイフ") == 0 && g.gold < item("ナイフ").map(|d| d.buy).unwrap_or(0) {
            // 先に家具屋などで使いきって お金が足りない: 出世払いで 一本 わたしてくれる
            v.push("あら、お金が 足りないの? しょうがないわね。出世払いで いいわ。".to_string());
            v.push("アレン「ありがとう、お姉さん! 必ず 返すよ。」".to_string());
            g.add_item("ナイフ", 1);
            let _ = g.equip(0, "ナイフ");
            v.push("＊ナイフを もらって そうびした!".to_string());
        }
        if kind == ShopKind::Magic {
            // はじめから並んでいる魔法・品物は あいさつで 紹介したことにする
            for (k, _) in magic_pending(g) {
                g.talks_seen.insert(k);
            }
        }
    }
    match kind {
        ShopKind::Furniture => {
            v.extend(furniture_lines(g, greeted));
            for n in g.furniture_stock() {
                g.talks_seen.insert(format!("furn:{}", n));
            }
        }
        ShopKind::Magic => {
            for (k, lines) in magic_pending(g) {
                g.talks_seen.insert(k);
                v.extend(lines);
            }
        }
        _ => {}
    }
    // 3日め以降: 魔物を まとめて 倒すと 獲得品が ふえる(村長の 豆知識。一度だけ)
    if kind == ShopKind::Mayor && battle_tip_pending(g) {
        g.talks_seen.insert("tip:multi".to_string());
        v.extend(battle_tip_lines());
    }
    if matches!(kind, ShopKind::Mayor | ShopKind::Magic | ShopKind::Armor) {
        for (k, lines) in remind_pending(g, kind) {
            g.talks_seen.insert(k);
            v.extend(lines);
        }
        for q in pending_orders(g, kind) {
            v.extend(order_lines(q, mei, greeted));
            g.talks_seen.insert(format!("order:{}", q.id));
            if !q.main {
                g.accept_quest(q.id);
            }
        }
    }
    clean(v, mei)
}

/// 町の地図で 赤い「!」を出すか(話を聞くことがある)
pub fn has_talk(g: &Game, kind: ShopKind) -> bool {
    if tour_pending(g, kind) {
        return true;
    }
    match kind {
        ShopKind::Furniture => !furniture_lines(g, false).is_empty(),
        ShopKind::Mayor => !pending_orders(g, kind).is_empty() || !remind_pending(g, kind).is_empty() || battle_tip_pending(g),
        ShopKind::Armor => !pending_orders(g, kind).is_empty() || !remind_pending(g, kind).is_empty(),
        ShopKind::Magic => !pending_orders(g, kind).is_empty() || !remind_pending(g, kind).is_empty() || magic_pending(g).iter().any(|(_, l)| !l.is_empty()),
        ShopKind::Plaza => false,
    }
}

