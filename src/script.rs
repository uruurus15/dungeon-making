// ---------------- クエストを頼まれるイベント ----------------

fn giver_matches(giver: Giver, kind: ShopKind) -> bool {
    matches!((giver, kind), (Giver::Mayor, ShopKind::Mayor) | (Giver::Magic, ShopKind::Magic) | (Giver::Armor, ShopKind::Armor))
}

/// その人の家に着いたとき、まだ頼まれていないクエスト(メインは お話だけ、サブは 頼まれたら受けた状態に)
pub fn pending_orders(g: &Game, kind: ShopKind) -> Vec<&'static Quest> {
    QUESTS
        .iter()
        .filter(|q| giver_matches(q.giver, kind) && g.quest_available(q) && !g.talks_seen.contains(&format!("order:{}", q.id)) && g.quest_state(q.id) != 2)
        .collect()
}

/// 依頼のイベントの台詞(1行ずつ表示される)
pub fn order_lines(q: &Quest, mei: bool, greeted: bool) -> Vec<String> {
    let (hello, bye) = match (q.giver, greeted) {
        (Giver::Mayor, false) => ("おお、アレン! ちょうどよいところに来た。", "頼んだぞ、アレン。"),
        (Giver::Magic, false) => ("おお、アレンか。ひとつ 頼まれてくれんか?", "待っておるぞ。"),
        (Giver::Armor, false) => ("あ、アレン! ちょうどよかった、お願いがあるの。", "お願いね!"),
        // あいさつまわりの続き(あいさつは もう済んでいる)
        (Giver::Mayor, true) => ("それと じゃ。ついでに ひとつ 頼みたいことが あっての。", "頼んだぞ、アレン。"),
        (Giver::Magic, true) => ("そうじゃ、ついでに ひとつ 頼まれてくれんか?", "待っておるぞ。"),
        (Giver::Armor, true) => ("あ、そうだ。ひとつ お願いが あるの。", "お願いね!"),
    };
    let mut v = vec![hello.to_string()];
    for l in q.text.split('\n') {
        v.push(l.to_string());
    }
    if q.prepay > 0 {
        v.push(format!("前金に {}G を渡しておくでな。", q.prepay));
    }
    if q.giver == Giver::Mayor && q.id.len() % 2 == 0 {
        v.push("メイミ「ちょっと村長、また無茶ぶり? アレンは 便利屋じゃないのよ!」".to_string());
        v.push("※アレン「まあまあ、メイミ。引き受けるよ。」".to_string());
    }
    v.push(bye.to_string());
    v.push(format!("＊クエスト「{}」を 受けた!", q.title));
    clean(v, mei)
}

