/// はじめからの ゲームか(あいさつまわりを するか)。古いセーブ・デバッグのプリセットは しない
pub fn tour_on(g: &Game) -> bool {
    g.talks_seen.contains("tour")
}

fn kind_key(kind: ShopKind) -> &'static str {
    match kind {
        ShopKind::Armor => "armor",
        ShopKind::Magic => "magic",
        ShopKind::Furniture => "furn",
        ShopKind::Plaza => "plaza",
        ShopKind::Mayor => "mayor",
    }
}

fn hello_key(kind: ShopKind) -> String {
    format!("hello:{}", kind_key(kind))
}

/// まだ あいさつしていない家か
pub fn tour_pending(g: &Game, kind: ShopKind) -> bool {
    tour_on(g) && !g.talks_seen.contains(&hello_key(kind))
}

/// あいさつまわりが まだ残っている家の数
pub fn tour_left(g: &Game) -> usize {
    [ShopKind::Armor, ShopKind::Magic, ShopKind::Furniture, ShopKind::Plaza, ShopKind::Mayor].iter().filter(|&&k| tour_pending(g, k)).count()
}

