/// 受けたクエストの そのあとのようす(まだ話していない物)
pub fn remind_pending(g: &Game, kind: ShopKind) -> Vec<(String, Vec<String>)> {
    QUEST_REMIND
        .iter()
        .filter_map(|(id, lines)| {
            let q = quest(id);
            let key = format!("remind:{}", id);
            let accepted_day = g.quests.get(*id).map(|x| x.1).unwrap_or(0);
            let ok = giver_matches(q.giver, kind) && g.quest_state(id) == 1 && g.day > accepted_day && !g.talks_seen.contains(&key) && g.count(q.need) < q.count;
            ok.then(|| (key, lines.iter().map(|l| fill(l, q)).collect()))
        })
        .collect()
}

