// ---------------- メイミが まだ仲間でないときの 台詞の整理 ----------------

thread_local! {
    /// ジェリーが 仲間か(毎フレーム App が 更新する。clean が 見て、まだなら ジェリーの台詞を 取りのぞく)
    static JERRY_JOINED: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
}

/// いまの パーティを 台詞の整理に 知らせる
pub fn sync_party(g: &Game) {
    JERRY_JOINED.with(|c| c.set(g.party.len() > 1 && g.party[1].joined));
}

/// メイミが仲間になる前は メイミの台詞と、メイミがいるから成り立つ行(頭に ※)を 取りのぞく。仲間なら ※だけ外す。
/// ジェリーも 仲間になる前は ジェリーの台詞(「ジェリー「」)を 取りのぞく
pub fn clean(lines: Vec<String>, mei: bool) -> Vec<String> {
    let jerry = JERRY_JOINED.with(|c| c.get());
    lines
        .into_iter()
        .filter(|l| mei || !(l.starts_with("メイミ「") || l.starts_with('※')))
        .filter(|l| jerry || !l.trim_start_matches('※').starts_with("ジェリー「"))
        .map(|l| l.trim_start_matches('※').to_string())
        .collect()
}

