    // ぶきかけ(うしろの かべ)
    m.rbox(0.0, 0.0, -1.38, 1.9, 0.05, 0.12, 0.01, col(110, 74, 40));
    m.rbox(-0.92, 0.05, -1.38, 0.06, 0.55, 0.1, 0.01, col(110, 74, 40));
