        m.ellipsoid([x, 0.98, z], [0.09, 0.09, 0.09], 8, 12, &|_, _| col(226, 192, 110));
        m.tube([x, 0.6, z], [x, 0.62, z], 0.095, 0.095, 10, col(220, 40, 40), true);
