    let mut m = Mb::new();
    let stone = col(160, 156, 150);
    m.jitter = 0.07;
    m.rbox(0.0, 0.0, 0.0, 0.92, 0.06, 0.74, 0.014, shadec(stone, 0.9));
    m.rbox(0.0, 0.06, 0.0, 0.74, 0.06, 0.54, 0.014, stone);
    m.rbox(0.0, 0.12, -0.02, 0.5, 0.3, 0.32, 0.016, shadec(stone, 1.08));
    m.jitter = 0.0;
    // 前の 彫りの 板と 金の 十字
