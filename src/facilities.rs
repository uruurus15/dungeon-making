//! 施設の 手組みモデル(その1: 1マスの 施設)。部品は modeling.rs。
//! 座標は 1マスの 中で x,z = -0.5..0.5、y=うえ。魔物が 手前の 右に 立つので、手前の 右は あけておく。

use crate::model3d::Model;
use crate::modeling::*;
use std::f32::consts::{PI, TAU};

fn arc_poly(z0: f32, z1: f32, y_base: f32, rise: f32, n: usize) -> Vec<(f32, f32)> {
    let mut v = vec![(z0, y_base), (z1, y_base)];
    for k in 0..=n {
        let a = k as f32 / n as f32;
        v.push((z1 + (z0 - z1) * a, y_base + rise * (a * PI).sin()));
    }
    v
}

/// エサおけ: 木の かいばおけ(あしが ななめ)に 穀物・にんじん・りんごが 山もり
pub fn feed_trough() -> Model {
    let mut m = Mb::new();
    let mut rnd = Rnd(3);
    let wood = col(140, 96, 54);
    let wood_d = col(98, 66, 36);
    m.jitter = 0.07;
    for x in [-0.34f32, 0.34] {
        for z in [-0.2f32, 0.2] {
            m.tube([x * 1.18, 0.0, z * 1.25], [x * 0.9, 0.24, z * 0.8], 0.032, 0.036, 8, wood_d, true);
        }
    }
    m.rbox(0.0, 0.2, 0.0, 0.8, 0.05, 0.4, 0.012, wood);
    for z in [-0.2f32, 0.2] {
        m.rbox(0.0, 0.22, z, 0.9, 0.14, 0.045, 0.012, wood);
    }
    for x in [-0.435f32, 0.435] {
        m.rbox(x, 0.22, 0.0, 0.045, 0.14, 0.4, 0.012, shadec(wood, 0.92));
    }
    m.jitter = 0.0;
    // 木の わっか(たが)
    for x in [-0.25f32, 0.25] {
        m.rbox(x, 0.215, 0.0, 0.035, 0.145, 0.452, 0.008, col(70, 66, 70));
    }
    // 穀物の 山
    // 縁(高さ 0.36)より ずっと 上まで こんもり もる
    let feed = |x: f32, z: f32| -> f32 { 0.33 + 0.24 * (1.0 - (x / 0.4).powi(2)).max(0.0).powf(0.55) * (1.0 - (z / 0.18).powi(2)).max(0.0).powf(0.5) + 0.014 * noise(x * 24.0, z * 24.0, 2.0) };
    m.heightfield(-0.4, 0.4, -0.18, 0.18, 34, 14, 0.0, &feed, &|x, z, _| {
        let n = noise(x * 30.0, z * 30.0, 5.0);
        mix(col(206, 164, 78), col(150, 108, 52), (n * 0.5 + 0.5) * 0.7)
    });
    // のっている やさい・くだもの
    for (x, z) in [(-0.24f32, 0.04f32), (0.1, -0.06), (0.28, 0.05)] {
        let y = feed(x, z);
        m.ellipsoid([x, y + 0.025, z], [0.05, 0.045, 0.05], 8, 12, &|th, _| mix(col(206, 52, 40), col(240, 120, 90), (1.0 - th / PI).powi(3)));
        m.tube([x, y + 0.065, z], [x + 0.005, y + 0.09, z], 0.006, 0.004, 5, col(80, 54, 28), false);
    }
    for (x, z, a) in [(-0.1f32, 0.0f32, 0.7f32), (0.2, -0.08, -0.5), (-0.3, -0.07, 0.2)] {
        let y = feed(x, z);
        m.tube([x - a.cos() * 0.05, y + 0.02, z - a.sin() * 0.05], [x + a.cos() * 0.06, y + 0.035, z + a.sin() * 0.06], 0.02, 0.006, 8, col(236, 130, 40), true);
        m.blade([x - a.cos() * 0.05, y + 0.02, z - a.sin() * 0.05], [-a.cos(), 0.7, -a.sin()], 0.4, 0.06, 0.012, col(80, 150, 60));
    }
    for _ in 0..40 {
        let (x, z) = (rnd.range(-0.38, 0.38), rnd.range(-0.15, 0.15));
        let a = rnd.range(0.0, TAU);
        m.blade([x, feed(x, z) - 0.01, z], [a.cos() * 0.4, 1.0, a.sin() * 0.4], 0.6, rnd.range(0.04, 0.08), 0.006, col(226, 190, 90));
    }
    // こぼれた つぶ
    for _ in 0..24 {
        let a = rnd.range(0.0, TAU);
        let (x, z) = (a.cos() * rnd.range(0.3, 0.5), a.sin() * rnd.range(0.26, 0.36));
        m.ellipsoid([x, 0.008, z], [0.014, 0.008, 0.01], 4, 6, &|_, _| col(206, 164, 78));
    }
    m.done()
}

#[derive(Clone, Copy, PartialEq)]
pub enum Metal {
    Iron,
    Silver,
    Gold,
}

/// たからばこ: 本体・まるい ふた・たが・かぎ・びょう。あけると ふたが 上に ひらき、中に 宝が みえる
pub fn chest(kind: Metal, open: bool) -> Model {
    let mut m = Mb::new();
    let mut rnd = Rnd(11);
    let (body, band, lock, coin, gem) = match kind {
        Metal::Iron => (col(112, 114, 124), col(62, 64, 72), col(200, 164, 70), col(186, 190, 200), col(80, 160, 220)),
        Metal::Silver => (col(190, 196, 210), col(236, 240, 250), col(224, 184, 70), col(224, 228, 238), col(70, 130, 230)),
        Metal::Gold => (col(226, 180, 58), col(252, 220, 110), col(210, 50, 56), col(250, 210, 80), col(220, 50, 70)),
    };
    let (bx0, bx1, hz) = (-0.4f32, 0.4f32, 0.25f32);
    let bh = 0.3;
    m.jitter = if kind == Metal::Iron { 0.06 } else { 0.03 };
    m.rbox(0.0, 0.0, 0.0, 0.8, bh, 0.5, 0.02, body);
    m.jitter = 0.0;
    m.rbox(0.0, 0.0, 0.0, 0.84, 0.045, 0.54, 0.01, band);
    for x in [-0.28f32, 0.0, 0.28] {
        m.rbox(x, 0.0, 0.0, 0.07, bh + 0.002, 0.512, 0.01, band);
    }
    let lid_poly = |scale: f32, zoff: f32, yoff: f32| -> Vec<(f32, f32)> { arc_poly(-hz * scale + zoff, hz * scale + zoff, yoff, 0.17 * scale, 14) };
    let lid = |m: &mut Mb, z_hinge: f32| {
        // ふたの ほんたい(まるい)と たが
        m.extrude_x(&lid_poly(1.0, z_hinge, 0.0), bx0, bx1, shadec(body, 1.05));
        for x in [-0.28f32, 0.0, 0.28] {
            m.extrude_x(&lid_poly(1.045, z_hinge, -0.005), x - 0.037, x + 0.037, band);
        }
        m.extrude_x(&lid_poly(1.05, z_hinge, -0.01), bx0 - 0.02, bx0 + 0.015, band);
        m.extrude_x(&lid_poly(1.05, z_hinge, -0.01), bx1 - 0.015, bx1 + 0.02, band);
    };
    // びょう
    for x in [-0.37f32, 0.37] {
        for z in [-0.22f32, 0.22] {
            m.ellipsoid([x, 0.27, z], [0.022, 0.022, 0.022], 5, 8, &|_, _| band);
            m.ellipsoid([x, 0.03, z], [0.022, 0.022, 0.022], 5, 8, &|_, _| band);
        }
    }
    if !open {
        m.at([0.0, bh, 0.0], 0.0, 0.0, 0.0, |m| lid(m, 0.0));
        // かぎ金具
        m.rbox(0.0, 0.17, 0.262, 0.11, 0.15, 0.025, 0.008, lock);
        m.ellipsoid([0.0, 0.24, 0.282], [0.02, 0.02, 0.01], 5, 8, &|_, _| col(30, 24, 20));
        m.rbox(0.0, 0.19, 0.285, 0.012, 0.045, 0.01, 0.0, col(30, 24, 20));
    } else {
        // うちがわ(くらい)と 宝の 山
        m.bx(0.0, bh - 0.004, 0.0, 0.72, 0.006, 0.44, col(54, 24, 28), false);
        let hoard = |x: f32, z: f32| -> f32 { bh + 0.015 + 0.075 * (1.0 - (x / 0.36).powi(2)).max(0.0).powf(0.6) * (1.0 - (z / 0.22).powi(2)).max(0.0).powf(0.6) + 0.01 * noise(x * 30.0, z * 30.0, 4.0) };
        m.heightfield(-0.35, 0.35, -0.21, 0.21, 28, 12, 0.0, &hoard, &|x, z, _| {
            let n = noise(x * 45.0, z * 45.0, 7.0) * 0.5 + 0.5;
            shadec(coin, 0.78 + 0.35 * n)
        });
        for _ in 0..22 {
            let (x, z) = (rnd.range(-0.32, 0.32), rnd.range(-0.18, 0.18));
            let a = rnd.range(0.0, 3.0);
            m.at([x, hoard(x, z) + 0.006, z], a, rnd.range(-0.5, 0.5), rnd.range(-0.5, 0.5), |m| m.tube([0.0, 0.0, 0.0], [0.0, 0.01, 0.0], 0.03, 0.03, 10, shadec(coin, 0.9 + 0.2 * rnd.next()), true));
        }
        for (x, z, c) in [(-0.14f32, 0.06f32, gem), (0.12, -0.05, col(60, 200, 110)), (0.2, 0.1, col(230, 70, 80))] {
            m.ellipsoid([x, hoard(x, z) + 0.02, z], [0.03, 0.03, 0.03], 5, 8, &|_, _| c);
        }
        // ひらいた ふた(うしろの ふちを 軸に ななめうしろへ)
        m.at([0.0, bh, -hz], 0.0, -1.95, 0.0, |m| lid(m, hz));
    }
    m.done()
}

/// さかば: たるの ビールだる、まるテーブルと ジョッキ、こしかけ(通れるように 低く かたすみに)
pub fn tavern() -> Model {
    let mut m = Mb::new();
    let wood = col(136, 90, 50);
    let wood_d = col(96, 62, 34);
    let iron = col(70, 66, 72);
    // ビールだる(うしろ左)
    let keg = [(0.0, 0.0), (0.12, 0.0), (0.135, 0.04), (0.16, 0.14), (0.17, 0.26), (0.16, 0.38), (0.135, 0.48), (0.12, 0.5), (0.0, 0.5)];
    m.lathe(-0.3, 0.0, -0.3, &keg, 18, &|i, j| shadec(wood, if j % 2 == 0 { 1.0 } else { 0.87 } * (0.95 + 0.04 * i as f32 % 1.0)));
    for (y, r) in [(0.08f32, 0.145f32), (0.4, 0.15)] {
        m.lathe(-0.3, y, -0.3, &[(r + 0.002, 0.0), (r + 0.01, 0.0), (r + 0.01, 0.025), (r + 0.002, 0.025)], 18, &|_, _| iron);
    }
    m.tube([-0.3, 0.16, -0.14], [-0.3, 0.16, -0.06], 0.014, 0.014, 8, col(190, 160, 70), true);
    m.tube([-0.3, 0.16, -0.06], [-0.3, 0.1, -0.06], 0.012, 0.012, 8, col(190, 160, 70), true);
    // まるテーブル(うしろ右)
    m.lathe(0.3, 0.0, -0.3, &[(0.0, 0.0), (0.12, 0.0), (0.12, 0.02), (0.04, 0.05), (0.04, 0.34), (0.22, 0.36), (0.23, 0.385), (0.0, 0.385)], 20, &|i, _| if i >= 4 { wood } else { wood_d });
    // ジョッキ(あわ つき)
    for (x, z, a) in [(0.24f32, -0.3f32, 0.3f32), (0.37, -0.25, 1.4)] {
        m.lathe(x, 0.385, z, &[(0.0, 0.0), (0.032, 0.0), (0.036, 0.012), (0.038, 0.08), (0.034, 0.082), (0.0, 0.08)], 12, &|_, _| col(210, 170, 60));
        m.ellipsoid([x, 0.468, z], [0.034, 0.014, 0.034], 6, 10, &|_, _| col(250, 246, 230));
        m.tube([x + a.cos() * 0.036, 0.42, z], [x + a.cos() * 0.055, 0.42, z], 0.006, 0.006, 6, col(190, 150, 50), false);
        m.tube([x + a.cos() * 0.055, 0.42, z], [x + a.cos() * 0.055, 0.45, z], 0.006, 0.006, 6, col(190, 150, 50), false);
    }
    // こしかけ(まるい)
    for (x, z) in [(0.3f32, -0.04f32), (0.06, -0.38)] {
        m.lathe(x, 0.0, z, &[(0.0, 0.0), (0.07, 0.0), (0.05, 0.02), (0.05, 0.2), (0.11, 0.22), (0.11, 0.25), (0.0, 0.25)], 14, &|i, _| if i >= 4 { wood } else { wood_d });
    }
    // ゆかの こぼれた おさけ
    m.ellipsoid([0.12, 0.003, -0.12], [0.09, 0.004, 0.06], 4, 10, &|_, _| col(190, 140, 40));
    m.done()
}

/// さいだん: 石の だんの 上の 祭壇。むらさきの 布、ろうそく、聖杯、ういている 水晶
