/// ベッドの 共通: style 0=りっぱなベッド(彫りの 板と 赤い かけぶとん)、1=ごうかなベッド(天がい・カーテン・金)
pub fn canopy_bed(luxury: bool) -> Model {
    let mut m = Mb::new();
    let mut rnd = Rnd(if luxury { 17 } else { 13 });
    let (wood, wood_d, trim) = if luxury { (col(204, 160, 62), col(160, 120, 40), col(250, 214, 110)) } else { (col(126, 84, 46), col(90, 58, 32), col(206, 168, 80)) };
    let cloth = if luxury { col(158, 32, 52) } else { col(150, 52, 52) };
    let (hx, hz) = (0.46f32, 0.3f32);
    m.jitter = 0.04;
    // あし
    for (x, z) in [(-hx, -hz), (hx, -hz), (-hx, hz), (hx, hz)] {
        m.lathe(x, 0.0, z, &[(0.0, 0.0), (0.04, 0.0), (0.05, 0.03), (0.035, 0.07), (0.035, 0.14), (0.045, 0.16), (0.0, 0.16)], 12, &|_, _| wood_d);
    }
    // わく
    m.rbox(0.0, 0.14, 0.0, 2.0 * hx, 0.1, 2.0 * hz, 0.02, wood);
    for z in [-hz, hz] {
        m.rbox(0.0, 0.12, z, 2.0 * hx + 0.04, 0.03, 0.05, 0.01, trim);
    }
    m.jitter = 0.0;
    // マットレス・シーツ
    m.rbox(0.0, 0.24, 0.0, 2.0 * hx - 0.06, 0.07, 2.0 * hz - 0.06, 0.03, col(238, 232, 214));
    let quilt = |x: f32, z: f32| -> f32 {
        let top = 0.31;
        let fz = (z.abs() - 0.18).max(0.0);
        top + 0.018 + 0.006 * (x * 30.0).sin() * (z * 22.0).cos() - fz * 0.7
    };
    m.heightfield(-0.04, 0.4, -0.3, 0.3, 16, 20, 0.2, &quilt, &|x, z, _| {
        let edge = (0.3 - z.abs()).min(0.4 - x);
        if edge < 0.045 {
            trim
        } else {
            shadec(cloth, 0.92 + 0.12 * noise(x * 28.0, z * 28.0, 4.0))
        }
    });
    // まくら
    for z in [-0.16f32, 0.16] {
        m.ellipsoid([-0.31, 0.37, z], [0.09, 0.05, 0.13], 9, 14, &|th, _| shadec(col(246, 240, 224), 0.9 + 0.15 * (1.0 - th / PI)));
    }
    // ヘッドボード(彫りの いたつき)
    let arch = |top: f32, rise: f32| -> Vec<(f32, f32)> {
        let mut v = vec![(-hz - 0.03, 0.1), (hz + 0.03, 0.1)];
        for k in 0..=12 {
            let a = k as f32 / 12.0;
            v.push((hz + 0.03 - (2.0 * hz + 0.06) * a, top + rise * (a * PI).sin()));
        }
        v
    };
    m.extrude_x(&arch(0.5, 0.1), -hx - 0.07, -hx - 0.01, wood_d);
    m.rbox(-hx + 0.0 - 0.0, 0.2, 0.0, 0.02, 0.0, 0.0, 0.0, wood); // (空)
    for z in [-0.15f32, 0.15] {
        m.rbox(-hx - 0.012, 0.26, z, 0.02, 0.26, 0.2, 0.01, shadec(wood, 1.12));
    }
    m.extrude_x(&arch(0.27, 0.04), hx + 0.01, hx + 0.07, wood_d);
    // しなやかな あしの 先の 飾り
    for (x, z) in [(-hx, -hz), (hx, -hz), (-hx, hz), (hx, hz)] {
        let top = if luxury { 0.9 } else { if x < 0.0 { 0.62 } else { 0.36 } };
        m.tube([x, 0.16, z], [x, top, z], 0.026, 0.022, 10, wood_d, false);
        m.ellipsoid([x, top + 0.02, z], [0.034, 0.034, 0.034], 8, 12, &|_, _| trim);
    }
    if luxury {
        // 天がい(布)と ふさ、カーテン
        let canopy = |x: f32, z: f32| -> f32 { 0.9 - 0.035 * (1.0 - (x / hx).powi(2)).max(0.0) * (1.0 - (z / hz).powi(2)).max(0.0) };
        m.heightfield(-hx, hx, -hz, hz, 18, 12, 0.0, &canopy, &|x, z, _| shadec(cloth, 0.9 + 0.2 * noise(x * 14.0, z * 14.0, 6.0)));
        for z in [-hz, hz] {
            m.rbox(0.0, 0.88, z, 2.0 * hx + 0.06, 0.03, 0.04, 0.008, trim);
        }
        for x in [-hx, hx] {
            m.rbox(x, 0.88, 0.0, 0.04, 0.03, 2.0 * hz, 0.008, trim);
        }
        // カーテン(ほうに たばねて 前の 左右 に たれる)
        m.drape(-hx - 0.04, -hx + 0.1, 0.88, 0.2, hz + 0.02, 3.0, true, cloth);
        m.drape(hx - 0.1, hx + 0.04, 0.88, 0.2, hz + 0.02, 3.0, true, cloth);
        for x in [-hx + 0.04, hx - 0.04] {
            m.lathe(x, 0.46, hz + 0.02, &[(0.0, 0.0), (0.035, 0.0), (0.02, 0.05), (0.0, 0.05)], 8, &|_, _| trim);
        }
        for i in 0..14 {
            let x = -hx + (2.0 * hx) * i as f32 / 13.0;
            m.ellipsoid([x, 0.855, hz + 0.01], [0.016, 0.025, 0.016], 4, 6, &|_, _| trim);
        }
        let _ = &mut rnd;
    }
    m.done()
}

